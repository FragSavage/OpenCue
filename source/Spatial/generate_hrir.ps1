param([Parameter(Mandatory=$true)][string]$KemarDirectory)
$ErrorActionPreference = 'Stop'
$dataFolder = Join-Path $PSScriptRoot 'data'
New-Item -ItemType Directory -Force -Path $dataFolder | Out-Null
$angles = @(0, 30, 90, 150)
$allResponses = [Collections.Generic.List[object]]::new()
$sourceFolder = Join-Path $KemarDirectory 'elev0'
if (!(Test-Path -LiteralPath $sourceFolder)) { $sourceFolder = $KemarDirectory }
foreach ($angle in $angles) {
    $name = 'H0e{0:D3}a.wav' -f $angle
    $path = Join-Path $sourceFolder $name
    $reader = [IO.BinaryReader]::new([IO.File]::OpenRead($path))
    try {
        if ([Text.Encoding]::ASCII.GetString($reader.ReadBytes(4)) -ne 'RIFF') { throw "Not a WAV: $path" }
        $null = $reader.ReadUInt32()
        if ([Text.Encoding]::ASCII.GetString($reader.ReadBytes(4)) -ne 'WAVE') { throw "Not a WAV: $path" }
        $format = $null; $pcm = $null
        while ($reader.BaseStream.Position + 8 -le $reader.BaseStream.Length) {
            $chunk = [Text.Encoding]::ASCII.GetString($reader.ReadBytes(4))
            $size = $reader.ReadUInt32()
            $next = $reader.BaseStream.Position + $size + ($size % 2)
            if ($chunk -eq 'fmt ') {
                $format = @($reader.ReadUInt16(), $reader.ReadUInt16(), $reader.ReadUInt32(), $reader.ReadUInt32(), $reader.ReadUInt16(), $reader.ReadUInt16())
            } elseif ($chunk -eq 'data') { $pcm = $reader.ReadBytes($size) }
            $reader.BaseStream.Position = $next
        }
        if (!$format -or $format[0] -ne 1 -or $format[1] -ne 2 -or $format[2] -ne 44100 -or $format[5] -ne 16 -or !$pcm -or $pcm.Length -ne 512) {
            throw "Expected stereo PCM16, 44.1 kHz, 128 frames: $path"
        }
        $left = [Collections.Generic.List[int]]::new(); $right = [Collections.Generic.List[int]]::new()
        for ($frame = 0; $frame -lt 128; $frame++) {
            $left.Add([BitConverter]::ToInt16($pcm, 4*$frame))
            $right.Add([BitConverter]::ToInt16($pcm, 4*$frame+2))
        }
        $allResponses.Add(@($left.ToArray(), $right.ToArray()))
    } finally { $reader.Dispose() }
    $destination = Join-Path $dataFolder $name
    if (![string]::Equals([IO.Path]::GetFullPath($path), [IO.Path]::GetFullPath($destination), [StringComparison]::OrdinalIgnoreCase)) {
        Copy-Item -LiteralPath $path -Destination $destination -Force
    }
}
$header = [Text.StringBuilder]::new()
[void]$header.AppendLine('/* Measured MIT KEMAR compact HRIR data. Copyright 1994 MIT Media Laboratory. */')
[void]$header.AppendLine('/* Bill Gardner and Keith Martin; see MIT-KEMAR-NOTICE.txt. Not an MIT software license. */')
[void]$header.AppendLine('/* Generated by generate_hrir.ps1 from the four unmodified PCM WAVs in data/. */')
[void]$header.AppendLine('#ifndef OPENCUE_KEMAR_HRIR_H')
[void]$header.AppendLine('#define OPENCUE_KEMAR_HRIR_H')
[void]$header.AppendLine('#include <stdint.h>')
[void]$header.AppendLine('static const int16_t oc_kemar_hrir[4][2][128] = {')
foreach ($response in $allResponses) {
    [void]$header.AppendLine('  {')
    foreach ($ear in $response) {
        [void]$header.AppendLine('    {')
        for ($i=0; $i -lt 128; $i+=16) { [void]$header.AppendLine('      ' + (($ear[$i..($i+15)] | ForEach-Object { [string]$_ }) -join ', ') + ',') }
        [void]$header.AppendLine('    },')
    }
    [void]$header.AppendLine('  },')
}
[void]$header.AppendLine('};')
[void]$header.AppendLine('#endif')
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'kemar_hrir.h'), $header.ToString(), [Text.UTF8Encoding]::new($false))
